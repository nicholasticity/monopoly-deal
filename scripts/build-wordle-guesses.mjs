// Writes src/wordle/guesses.js: every five-letter word in the word-list package
// (MIT, https://github.com/sindresorhus/word-list) that isn't already a secret word.
// Usage: npx --package word-list@4 node scripts/build-wordle-guesses.mjs
//   or:  node scripts/build-wordle-guesses.mjs path/to/words.txt
import fs from 'node:fs';
import { ANSWERS } from '../src/wordle/answers.js';

const path = process.argv[2] ?? (await import('word-list')).default;
const all = fs.readFileSync(path, 'utf8').split('\n').map((w) => w.trim());
const answers = new Set(ANSWERS);
const words = [...new Set(all.filter((w) => /^[a-z]{5}$/.test(w) && !answers.has(w)))].sort();

for (const w of ANSWERS) if (!all.includes(w)) console.warn(`not in the word list: ${w}`);

// One long string keeps the file small; split once on load.
const out = `// Five-letter words accepted as guesses, besides the secret words in answers.js.
// Generated by scripts/build-wordle-guesses.mjs from the word-list package
// (MIT License, Copyright (c) Sindre Sorhus). Don't edit by hand.
export const GUESSES = '${words.join(' ')}'.split(' ');
`;
fs.writeFileSync(new URL('../src/wordle/guesses.js', import.meta.url), out);
console.log(`${words.length} extra guesses, ${ANSWERS.length} secret words`);
